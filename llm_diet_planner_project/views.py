import os
import logging
from django.http import HttpResponse
from django.conf import settings

logger = logging.getLogger(__name__)

def react_app_view(request):
    """
    Serves the React frontend. In production, this looks for the index.html 
    inside the 'dist' folder generated by Vite.
    """
    index_path = os.path.join(settings.REACT_BUILD_DIR, 'index.html')
    
    if not os.path.exists(index_path):
        logger.error(f"Frontend build not found at {index_path}")
        return HttpResponse(
            f"""
            <html>
                <body style="background: #0a0f1e; color: white; text-align: center; font-family: sans-serif; padding-top: 100px;">
                    <h1>Vite Build Missing</h1>
                    <p>Expected index.html at: <code>{index_path}</code></p>
                    <p>Current Working Directory: <code>{os.getcwd()}</code></p>
                    <hr style="width: 50%; border: 1px solid #161d2f;">
                    <p>Check deployment logs for Vite build errors.</p>
                </body>
            </html>
            """,
            status=503
        )

    with open(index_path, 'r') as f:
        return HttpResponse(f.read())